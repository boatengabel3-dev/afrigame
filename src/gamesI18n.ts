export function getLocalizedGame(g: Game, lang: Language): Game {
  if (lang === 'en') return g;
  const loc = GAMES_I18N[g.id]?.[lang];
  if (!loc) return g;

  return {
    ...g,
    name: loc.name || g.name,
    category: (loc.category as any) || g.category,
    players: loc.players || g.players,
    level: (loc.level as any) || g.level,
    origin: loc.origin || g.origin,
    format: loc.format || g.format,
    summary: loc.summary || g.summary,
    rules: loc.rules || g.rules,
    history: loc.history || g.history,
    equipment: loc.equipment || g.equipment,
    glossary: loc.glossary || g.glossary,
  };
}
